/*
TapCall Gradle Settings Configuration

Purpose:
- Defines the Gradle project structure and plugin management for TapCall Android
- Configures Flutter SDK integration and plugin versions
- Specifies which modules are included in the build

Key Components:
1. Plugin Management:
    - Reads flutter.sdk path from local.properties (generated by Flutter)
    - Includes Flutter's Gradle tooling from the SDK
    - Defines repository sources for Gradle plugins

2. Plugin Versions:
    - flutter-plugin-loader: 1.0.0 (Flutter's plugin loader)
    - Android Gradle Plugin: 8.6.1 (Google's Android build tools)
    - Kotlin Android Plugin: 2.1.0 (JetBrains Kotlin support)

3. Project Modules:
    - :app - The main TapCall application module (see app/build.gradle.kts)

Dependencies:
- Requires local.properties with flutter.sdk path (auto-generated by `flutter run`)
- Flutter SDK must be installed and accessible at the specified path

Notes:
- This file is read before any build scripts execute
- Plugin versions should be updated periodically for security and features
- The flutter.sdk path is machine-specific and should not be committed to git
*/

pluginManagement {
    val flutterSdkPath =
        run {
            val properties = java.util.Properties()
            file("local.properties").inputStream().use { properties.load(it) }
            val flutterSdkPath = properties.getProperty("flutter.sdk")
            require(flutterSdkPath != null) { "flutter.sdk not set in local.properties" }
            flutterSdkPath
        }

    includeBuild("$flutterSdkPath/packages/flutter_tools/gradle")

    repositories {
        google()
        mavenCentral()
        gradlePluginPortal()
    }
}

plugins {
    id("dev.flutter.flutter-plugin-loader") version "1.0.0"
    id("com.android.application") version "8.6.1" apply false
    id("org.jetbrains.kotlin.android") version "2.1.0" apply false
}

include(":app")
